const store = new Map<string, string>();
jest.mock('@react-native-async-storage/async-storage', () => ({
  __esModule: true,
  default: {
    getItem: jest.fn(async (key: string) => store.get(key) ?? null),
    setItem: jest.fn(async (key: string, value: string) => {
      store.set(key, value);
    }),
    removeItem: jest.fn(async (key: string) => {
      store.delete(key);
    }),
  },
}));

import { canSaveState, clearSavedRun, loadSavedRun, restoredState, saveRun } from '../../src/services/savedRun';
import { gameReducer } from '../../src/core/engine/reducer';
import { generateBoard } from '../../src/core/engine/generator';
import { initialState } from '../../src/core/engine/reducer';
import type { GameState } from '../../src/core/engine/types';
import characters from '../../src/data/characters';

const KEY = 'grimbur.run.v1';

/** A real mid-run state: floor 1 generated by the engine, two steps taken. */
function midRunState(mode: 'expedition' | 'endless' | 'daily' = 'expedition'): GameState {
  const board = generateBoard(1, 12345, { boss: false, ascension: 0, omen: null, biome: 'cave' });
  let s = gameReducer(initialState, {
    type: 'RESET',
    character: characters[0],
    rows: board.rows,
    cols: board.cols,
    entities: board.entities,
    coins: board.coins,
    attack: board.attack,
    seed: 12345,
    runSeed: 12345,
    mode,
  });
  s = gameReducer(s, { type: 'MOVE', direction: 'RIGHT' });
  if (s.isGameOver) s = { ...s, isGameOver: false, deathCause: null }; // the test needs a live hero, not a lucky board
  return s;
}

describe('saved run', () => {
  beforeEach(() => store.clear());

  it('saves a mid-expedition state and loads it back with the hero reattached', async () => {
    const s = midRunState();
    await saveRun({ characterIndex: 2, skin: 'classic', ascension: 1, time: 95, state: s });

    const raw = store.get(KEY);
    expect(raw).toBeTruthy();
    // The hero pictures are not written: require ids change between app versions.
    expect(JSON.parse(raw as string).state.selectedCharacter).toBeNull();

    const loaded = await loadSavedRun();
    expect(loaded).not.toBeNull();
    expect(loaded!.characterIndex).toBe(2);
    expect(loaded!.time).toBe(95);
    expect(loaded!.state.playerIndex).toBe(s.playerIndex);
    expect(loaded!.state.score).toBe(s.score);

    const restored = restoredState(loaded!, characters[2]);
    expect(restored.selectedCharacter).toBe(characters[2]);
  });

  it('never saves a daily, a finished run or the window between floors', async () => {
    expect(canSaveState(midRunState('daily'))).toBe(false);
    expect(canSaveState({ ...midRunState(), isGameOver: true })).toBe(false);
    expect(canSaveState({ ...midRunState(), isVictory: true })).toBe(false);
    expect(canSaveState({ ...midRunState(), isLevelUp: true })).toBe(false);
    expect(canSaveState({ ...midRunState(), pendingDraft: ['quiver'] })).toBe(false);

    await saveRun({ characterIndex: 0, skin: 'classic', ascension: 0, time: 1, state: midRunState('daily') });
    expect(store.has(KEY)).toBe(false);
  });

  it('discards a save it cannot trust', async () => {
    store.set(KEY, 'not json at all');
    expect(await loadSavedRun()).toBeNull();
    expect(store.has(KEY)).toBe(false);

    store.set(KEY, JSON.stringify({ v: 999 }));
    expect(await loadSavedRun()).toBeNull();

    // A run that ended must not be offered to continue, even if it was written by hand.
    const over = { ...midRunState(), isGameOver: true };
    store.set(KEY, JSON.stringify({ v: 1, at: Date.now(), characterIndex: 0, skin: 'classic', ascension: 0, time: 5, state: over }));
    expect(await loadSavedRun()).toBeNull();
  });

  it('clears the save', async () => {
    await saveRun({ characterIndex: 0, skin: 'classic', ascension: 0, time: 10, state: midRunState() });
    expect(store.has(KEY)).toBe(true);
    await clearSavedRun();
    expect(store.has(KEY)).toBe(false);
  });

  it('RESTORE puts the saved state back into the engine unchanged', () => {
    const s = midRunState('endless');
    const out = gameReducer(initialState, { type: 'RESTORE', state: s });
    // The reducer's outer pass restarts the per-floor rescue count; everything else must come back as saved.
    expect(out).toEqual({ ...s, lairRescues: 0 });
  });
});
